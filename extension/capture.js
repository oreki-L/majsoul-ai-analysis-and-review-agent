(function () {
  'use strict';
  if (window.__MJ_OBSERVER_CAPTURE_V1__) return;
  Object.defineProperty(window, '__MJ_OBSERVER_CAPTURE_V1__', { value: true });
  const P = window.__MJ_OBSERVER_PROTOCOL_V1__;
  const CHANNEL = 'mj-observer-v1', epoch = Math.random().toString(36).slice(2);
  const recent = [], recordUrls = new Set();
  let sequence = 0, latestReplay = null, statusTimer;
  const stats = { sockets: 0, incoming: 0, outgoing: 0, gameEvents: 0, errors: 0, replayRecords: 0 };
  function emit(type, payload, remember = true) {
    const message = { channel: CHANNEL, epoch, sequence: ++sequence, type, payload };
    if (remember) { recent.push(message); if (recent.length > 300) recent.shift(); }
    window.postMessage(message, location.origin);
  }
  function status() {
    if (statusTimer) return;
    statusTimer = setTimeout(() => { statusTimer = null; emit('status', { ...stats }, false); }, 500);
  }
  function error(stage, exception) {
    stats.errors++;
    // Exceptions are generated by our parser, never server payloads or request URLs.
    emit('diagnostic', { stage, message: String(exception.message || '解析失败').slice(0, 220) }); status();
  }
  function gameEvent(event, socketId) {
    stats.gameEvents++;
    emit('event', { ...event, socketId }); status();
  }
  function readReplay(data) {
    try {
      const records = P.replay(data);
      latestReplay = { records }; stats.replayRecords = records.length;
      emit('replay', latestReplay, false); status();
    } catch (e) { error('牌谱解码', e); }
  }
  function safeRecordUrl(raw) {
    try {
      const u = new URL(raw, location.href);
      // Only observe a URL explicitly returned in a game-record response. Never fetch it ourselves.
      if (u.protocol === 'https:') { recordUrls.add(u.href); if (recordUrls.size > 20) recordUrls.delete(recordUrls.values().next().value); }
    } catch (_) { /* No URL is exposed to the overlay or export. */ }
  }
  function restore(data, socketId) {
    const f = P.wire(data);
    if (P.blob(f, 1)?.length) throw new Error('服务器返回恢复错误');
    const restoreBytes = P.blob(f, 4);
    if (!restoreBytes) return;
    const restored = P.wire(restoreBytes), snapshot = P.blob(restored, 1);
    // A snapshot must not be treated as an empty fresh game.
    if (snapshot?.length) emit('diagnostic', { stage: '断线恢复', message: '收到局面快照，首版尚不支持；请重新从开局采集。' });
    // Fixed Akagi 91cc2993 and live syncGame traces from 2026-11-06 use
    // unmasked protobuf here; snapshot restoration remains unsupported.
    // Decode the whole batch before publishing, so a malformed tail cannot
    // leave a partially rebuilt opening marked complete.
    const actions = P.blobs(restored, 2).map(b => P.action(b, 'plain'));
    for (const event of actions) gameEvent({ ...event, restored: true }, socketId);
  }
  function inspect(buffer, direction, pending, socketId) {
    if (direction === 'sent') stats.outgoing++; else stats.incoming++;
    status();
    let f;
    try { f = P.frame(buffer); }
    catch (_) { return; } // Unrelated envelopes are not retained.
    if (f.type === 2 && direction === 'sent') {
      pending.delete(f.id);
      if (f.name === '.lq.FastTest.authGame') {
        // Retain only the numeric identity needed for the paired response;
        // tokens, sessions and the account id never leave this socket closure.
        pending.set(f.id, { method: f.name, account: P.num(P.wire(f.data), 1) >>> 0 });
      }
      if (['.lq.Lobby.fetchGameRecord', '.lq.FastTest.syncGame', '.lq.FastTest.enterGame'].includes(f.name)) {
        pending.set(f.id, f.name);
      }
      if (pending.size > 256) pending.delete(pending.keys().next().value);
    } else if (f.type === 1 && direction === 'received' && f.name === '.lq.ActionPrototype') {
      try { gameEvent(P.action(f.data), socketId); }
      catch (e) { error('动作解码', e); }
    } else if (f.type === 3 && direction === 'received') {
      const request = pending.get(f.id); pending.delete(f.id);
      const method = typeof request === 'string' ? request : request?.method;
      if (!method) return;
      try {
        if (method === '.lq.FastTest.authGame') {
          const response = P.wire(f.data), seats = P.nums(response, 3).map(n => n >>> 0);
          if (P.blob(response, 1)?.length) throw new Error('服务器返回认证错误');
          const seat = seats.indexOf(request.account);
          if (![3, 4].includes(seats.length) || request.account <= 0 || seat < 0 || seats.lastIndexOf(request.account) !== seat) throw new Error('认证座位无法识别');
          gameEvent({ kind: 'Seat', source: 'live', seat }, socketId);
        } else if (method === '.lq.Lobby.fetchGameRecord') {
          const record = P.recordResponse(f.data);
          if (record.url) safeRecordUrl(record.url);
          if (record.data?.length) readReplay(record.data);
          else if (record.url) emit('diagnostic', { stage: '牌谱载入', message: '已识别牌谱下载，等待游戏读取记录。' });
        } else restore(f.data, socketId);
      } catch (e) { error('牌局响应', e); }
    }
  }
  function isGameSocket(raw) {
    try { const u = new URL(String(raw), location.href); return /(^|\.)maj-soul\.com$/.test(u.hostname) && /gateway/.test(u.pathname); }
    catch (_) { return false; }
  }
  const NativeWebSocket = window.WebSocket;
  const ObservedWebSocket = new Proxy(NativeWebSocket, {
    construct(target, args, newTarget) {
      const socket = Reflect.construct(target, args, newTarget);
      if (!isGameSocket(args[0])) return socket;
      const pending = new Map(), socketId = ++stats.sockets;
      let receiveQueue = Promise.resolve();
      const nativeSend = socket.send;
      socket.send = function (data) {
        // Preserve native validation/throw behavior before recording a successful send.
        const result = Reflect.apply(nativeSend, this, [data]);
        if (this === socket) {
          try { if (typeof data !== 'string' && !(data instanceof Blob)) inspect(data, 'sent', pending, socketId); }
          catch (_) { /* Observation cannot interrupt the game. */ }
        }
        return result;
      };
      socket.addEventListener('message', event => {
        const data = event.data;
        receiveQueue = receiveQueue.then(async () => {
          if (typeof data === 'string') return;
          inspect(data instanceof Blob ? await data.arrayBuffer() : data, 'received', pending, socketId);
        }).catch(e => error('消息读取', e));
      });
      socket.addEventListener('open', () => emit('connection', { socketId, state: 'open' }));
      socket.addEventListener('close', () => {
        // Blob decoding already queued before close must precede invalidation.
        receiveQueue = receiveQueue.then(() => { pending.clear(); emit('connection', { socketId, state: 'closed' }); });
      });
      status();
      return socket;
    }
  });
  window.WebSocket = ObservedWebSocket;
  const nativeFetch = window.fetch;
  window.fetch = function (...args) {
    return Reflect.apply(nativeFetch, this, args).then(response => {
      let raw = args[0] instanceof Request ? args[0].url : String(args[0]);
      try { raw = new URL(raw, location.href).href; } catch (_) { return response; }
      if (recordUrls.has(raw) || recordUrls.has(response.url)) {
        const length = Number(response.headers.get('content-length'));
        if (length > P.MAX_BYTES) error('牌谱下载', new Error('牌谱超过16MiB限制'));
        else response.clone().arrayBuffer().then(readReplay).catch(e => error('牌谱读取', e));
      }
      return response;
    });
  };
  const xhrOpen = XMLHttpRequest.prototype.open, xhrSend = XMLHttpRequest.prototype.send;
  const xhrUrls = new WeakMap();
  XMLHttpRequest.prototype.open = function (...args) {
    const result = Reflect.apply(xhrOpen, this, args);
    try { xhrUrls.set(this, new URL(String(args[1]), location.href).href); } catch (_) { xhrUrls.delete(this); }
    return result;
  };
  XMLHttpRequest.prototype.send = function (...args) {
    if (recordUrls.has(xhrUrls.get(this))) this.addEventListener('load', async () => {
      try {
        if (this.status < 200 || this.status >= 300) return;
        if (this.response instanceof ArrayBuffer) readReplay(this.response);
        else if (this.response instanceof Blob) readReplay(await this.response.arrayBuffer());
        else error('牌谱读取', new Error('牌谱下载不是二进制响应'));
      } catch (e) { error('牌谱读取', e); }
    }, { once: true });
    return Reflect.apply(xhrSend, this, args);
  };
  window.addEventListener('message', event => {
    if (event.source !== window || event.origin !== location.origin || event.data?.channel !== CHANNEL || event.data?.type !== 'hello') return;
    for (const message of recent) window.postMessage(message, location.origin);
    if (latestReplay) emit('replay', latestReplay, false);
    emit('status', { ...stats }, false);
  });
  emit('diagnostic', { stage: '采集器', message: '已就绪，等待页面建立新连接。已载入的牌谱需重新打开。' });
})();
